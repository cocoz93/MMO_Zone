#if USE_INVENTORY

// ==========================================================================
// Item — 아이템 한 덩이: 무엇(itemId)이 몇 개(count)
//
// [ItemDef 와의 짝] ItemDef 는 정의(아이템 표 한 줄 — 이게 무엇이고 몇 개까지 쌓이나)이고,
//        Item 은 실물(몇 개가 어디에 있나)이다. 가방 칸도, 땅에 떨어진 아이템도 이것을 든다 —
//        그래서 줍기는 Item 하나를 땅에서 가방으로 옮기는 일이 된다.
//
// [파생 클래스 없음] 장비·물약의 차이는 ItemDef 의 데이터(탭·쌓임 한도·회복량)에 있다.
//        종류마다 클래스를 두지 않고, 가상 함수도 안 쓴다(Character.h [가상 함수]).
//
// [나중에 붙을 것] 고유 번호·개별 속성(강화·내구도) — 같은 종류끼리 구별할 일이 생기는 날 여기에 붙인다.
//        그러면 가방·땅이 같이 따라온다.
// ==========================================================================
struct Item
{
    int32_t itemId = 0;   // 0 = 없음(빈 칸)
    int32_t count  = 0;
};

#endif // USE_INVENTORY
